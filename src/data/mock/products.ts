import type { ImageKey, Product, ProductTag, ProductVariant } from '@/types/catalog'
import { naira, slugify } from '@/lib/format'

/**
 * Launch catalog. Deliberately small — the growth team pushes these on socials,
 * reads the feedback, and only then do we widen the range.
 * Copy rule: promise a price and a delivery window, never an adjective alone.
 */

type Seed = {
  name: string
  hook: string
  brand: string
  categoryId: string
  imageKey: ImageKey
  price: number
  was?: number
  stock?: number
  rating: number
  reviews: number
  sold: number
  tags?: ProductTag[]
  bullets: string[]
  description: string
  options?: { optionName: string; labels: string[]; delta?: number[] }
  deliveryDays?: [number, number]
  pod?: boolean
  daysOld?: number
}

let counter = 0

function make(seed: Seed): Product {
  counter += 1
  const id = `prd_${String(counter).padStart(3, '0')}`
  const priceKobo = naira(seed.price)
  const variants: ProductVariant[] = seed.options
    ? seed.options.labels.map((label, i) => ({
        id: `${id}_v${i + 1}`,
        label,
        optionName: seed.options!.optionName,
        priceKobo: priceKobo + naira(seed.options!.delta?.[i] ?? 0),
        stock: Math.max(2, Math.round((seed.stock ?? 40) / seed.options!.labels.length)),
        sku: `${id.toUpperCase()}-${slugify(label).toUpperCase()}`,
      }))
    : []

  const created = new Date(Date.now() - (seed.daysOld ?? 30) * 86400000).toISOString()

  return {
    id,
    slug: slugify(seed.name),
    name: seed.name,
    hook: seed.hook,
    description: seed.description,
    bullets: seed.bullets,
    brand: seed.brand,
    categoryId: seed.categoryId,
    imageKey: seed.imageKey,
    imageUrl: null,
    gallery: [],
    priceKobo,
    compareAtKobo: seed.was ? naira(seed.was) : null,
    stock: seed.stock ?? 40,
    variants,
    rating: seed.rating,
    reviewCount: seed.reviews,
    unitsSold: seed.sold,
    tags: ['back-to-school', ...(seed.tags ?? [])],
    deliveryDaysMin: seed.deliveryDays?.[0] ?? 14,
    deliveryDaysMax: seed.deliveryDays?.[1] ?? 14,
    payOnDelivery: seed.pod ?? true,
    createdAt: created,
    active: true,
  }
}

