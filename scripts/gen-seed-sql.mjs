// Generates supabase/seed.sql from the same demo catalog that powers mock
// mode, so a freshly-provisioned Supabase project starts with a real-looking
// store instead of an empty one. Not part of the app bundle — run manually
// (see HANDOFF.md) whenever the demo catalog in src/data/mock/ changes.
//
//   node scripts/gen-seed-sql.mjs > supabase/seed.sql
//
// Deliberately dependency-free (beyond the `typescript` devDependency
// already in node_modules): a tiny CommonJS loader that transpiles just the
// handful of mock-data files actually needed, so this never breaks because
// some unrelated bundler plugin isn't available in this context.
import ts from 'typescript'
import { createHash } from 'node:crypto'
import { fileURLToPath } from 'node:url'
import { readFileSync } from 'node:fs'
import path from 'node:path'
import Module from 'node:module'

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..')
const srcRoot = path.join(root, 'src')
const cache = new Map()

function resolveImport(spec, fromFile) {
  let base
  if (spec.startsWith('@/')) base = path.join(srcRoot, spec.slice(2))
  else if (spec.startsWith('.')) base = path.join(path.dirname(fromFile), spec)
  else return null // bare npm import — not expected for these files
  for (const ext of ['.ts', '.tsx', '/index.ts']) {
    const candidate = base + ext
    try {
      readFileSync(candidate)
      return candidate
    } catch {
      /* try next */
    }
  }
  throw new Error(`Cannot resolve "${spec}" from ${fromFile}`)
}

function loadTs(absPath) {
  if (cache.has(absPath)) return cache.get(absPath)
  const source = readFileSync(absPath, 'utf8')
  const out = ts.transpileModule(source, {
    compilerOptions: {
      module: ts.ModuleKind.CommonJS,
      target: ts.ScriptTarget.ES2020,
      esModuleInterop: true,
    },
    fileName: absPath,
  })
  const mod = { exports: {} }
  cache.set(absPath, mod.exports) // set before executing, for circular imports
  const localRequire = (spec) => {
    const resolved = resolveImport(spec, absPath)
    if (!resolved) return Module.createRequire(absPath)(spec)
    return loadTs(resolved)
  }
  const fn = new Function('module', 'exports', 'require', '__filename', '__dirname', out.outputText)
  fn(mod, mod.exports, localRequire, absPath, path.dirname(absPath))
  cache.set(absPath, mod.exports)
  return mod.exports
}

// Deterministic UUID (v5-ish — not a byte-for-byte RFC5282 hash, just a
// stable, validly-shaped UUID) so re-running this script against the same
// mock data keeps producing the same ids.
function uuidFor(namespace, key) {
  const hash = createHash('sha1').update(`tancha:${namespace}:${key}`).digest('hex')
  return [
    hash.slice(0, 8),
    hash.slice(8, 12),
    '5' + hash.slice(13, 16),
    ((parseInt(hash[16], 16) & 0x3) | 0x8).toString(16) + hash.slice(17, 20),
    hash.slice(20, 32),
  ].join('-')
}

function sqlStr(v) {
  if (v === null || v === undefined) return 'null'
  return `'${String(v).replace(/'/g, "''")}'`
}
function sqlArr(v) {
  if (!v || v.length === 0) return "'{}'"
  return `ARRAY[${v.map(sqlStr).join(',')}]::text[]`
}
function sqlBool(v) {
  return v ? 'true' : 'false'
}
function sqlNum(v) {
  return v === null || v === undefined ? 'null' : String(v)
}

function main() {
  const { categories } = loadTs(path.join(srcRoot, 'data/mock/categories.ts'))
  const { products } = loadTs(path.join(srcRoot, 'data/mock/products.ts'))
  const { deals } = loadTs(path.join(srcRoot, 'data/mock/deals.ts'))

  const catUuid = new Map(categories.map((c) => [c.id, uuidFor('category', c.id)]))
  const prodUuid = new Map(products.map((p) => [p.id, uuidFor('product', p.id)]))
  const varUuid = new Map()
  for (const p of products) for (const v of p.variants) varUuid.set(v.id, uuidFor('variant', v.id))
  const dealUuid = new Map(deals.map((d) => [d.id, uuidFor('deal', d.id)]))

  const lines = []
  lines.push('-- Generated by scripts/gen-seed-sql.mjs — do not hand-edit.')
  lines.push('-- Same demo catalog shown in mock mode, so a fresh Supabase project')
  lines.push('-- is not an empty store. Safe to skip, or delete everything before a real launch.')
  lines.push('')

  lines.push('-- ── Categories ──────────────────────────────────────────────────')
  for (const c of categories) {
    lines.push(
      `insert into categories (id, slug, name, image_key, parent_id, featured, position) values ` +
        `(${sqlStr(catUuid.get(c.id))}, ${sqlStr(c.slug)}, ${sqlStr(c.name)}, ${sqlStr(c.imageKey)}, null, ${sqlBool(c.featured)}, 0) ` +
        `on conflict (slug) do nothing;`,
    )
  }
  lines.push('')

  lines.push('-- ── Products ────────────────────────────────────────────────────')
  for (const p of products) {
    lines.push(
      `insert into products (id, slug, name, hook, description, bullets, brand, category_id, image_key, ` +
        `price_kobo, compare_at_kobo, stock, rating, review_count, units_sold, tags, delivery_days_min, ` +
        `delivery_days_max, pay_on_delivery, active) values (` +
        [
          sqlStr(prodUuid.get(p.id)),
          sqlStr(p.slug),
          sqlStr(p.name),
          sqlStr(p.hook),
          sqlStr(p.description),
          sqlArr(p.bullets),
          sqlStr(p.brand),
          sqlStr(catUuid.get(p.categoryId)),
          sqlStr(p.imageKey),
          sqlNum(p.priceKobo),
          sqlNum(p.compareAtKobo),
          sqlNum(p.stock),
          sqlNum(p.rating),
          sqlNum(p.reviewCount),
          sqlNum(p.unitsSold),
          sqlArr(p.tags),
          sqlNum(p.deliveryDaysMin),
          sqlNum(p.deliveryDaysMax),
          sqlBool(p.payOnDelivery),
          sqlBool(p.active),
        ].join(', ') +
        `) on conflict (slug) do nothing;`,
    )
    for (const v of p.variants) {
      lines.push(
        `insert into product_variants (id, product_id, option_name, label, price_kobo, stock, sku) values ` +
          `(${sqlStr(varUuid.get(v.id))}, ${sqlStr(prodUuid.get(p.id))}, ${sqlStr(v.optionName)}, ${sqlStr(v.label)}, ${sqlNum(v.priceKobo)}, ${sqlNum(v.stock)}, ${sqlStr(v.sku)}) ` +
          `on conflict (sku) do nothing;`,
      )
    }
  }
  lines.push('')

  lines.push('-- ── Deals ───────────────────────────────────────────────────────')
  for (const d of deals) {
    lines.push(
      `insert into deals (id, kind, title, subtitle, starts_at, ends_at, headline_discount, active) values ` +
        `(${sqlStr(dealUuid.get(d.id))}, ${sqlStr(d.kind)}, ${sqlStr(d.title)}, ${sqlStr(d.subtitle)}, ${sqlStr(d.startsAt)}, ${sqlStr(d.endsAt)}, ${sqlNum(d.headlineDiscount)}, ${sqlBool(d.active)}) ` +
        `on conflict (id) do nothing;`,
    )
    for (const pid of d.productIds) {
      const puid = prodUuid.get(pid)
      if (!puid) continue
      lines.push(
        `insert into deal_products (deal_id, product_id) values (${sqlStr(dealUuid.get(d.id))}, ${sqlStr(puid)}) on conflict do nothing;`,
      )
    }
  }
  lines.push('')
  lines.push(
    `-- Note: deals.starts_at/ends_at above are relative to when this file was generated\n` +
      `-- (${new Date().toISOString()}), not to when you run it. Regenerate close to launch\n` +
      `-- so the countdowns make sense, or edit deal dates from the admin console afterwards.`,
  )

  process.stdout.write(lines.join('\n') + '\n')
}

main()
